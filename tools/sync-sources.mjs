import {readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync} from 'node:fs';
import {resolve, join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';

const root = resolve(import.meta.dirname, '..');
const args = process.argv.slice(2);
if (!args[0] || args[0].startsWith('--')) {
  throw Error('Usage: node tools/sync-sources.mjs <RTL checkout> [--evidence-dir <normalized reports>]');
}
const rtl = resolve(args.shift());
let evidenceDir;
while (args.length) {
  const option = args.shift();
  if (option !== '--evidence-dir' || !args[0]) throw Error('Unknown or incomplete option: ' + option);
  evidenceDir = resolve(args.shift());
}
const commit = execFileSync('git', ['rev-parse', 'HEAD'], {cwd:rtl, encoding:'utf8'}).trim();
const dirty = execFileSync('git', ['status', '--porcelain', '--', 'rtl/design', 'rtl/verif', 'synth/foc_synth_wrapper.sv'], {cwd:rtl, encoding:'utf8'}).trim();
if (dirty) throw Error('Commit design, testbench and wrapper source changes before creating permanent source links.');
const files = [];
for (const dir of ['rtl/design', 'rtl/verif', 'synth']) {
  for (const name of readdirSync(join(rtl, dir)).filter(n => n.endsWith('.sv')).sort()) {
    const path = `${dir}/${name}`;
    const code = readFileSync(join(rtl, path), 'utf8').replace(/\r\n/g, '\n');
    files.push({path, name, code, sha256:createHash('sha256').update(code).digest('hex'),
      url:`https://github.com/spenchh/FPGA-foc-motor-control/blob/${commit}/${path}`});
  }
}
// A normal source refresh preserves historical implementation reports. Importing
// normalized reports is explicit and does not claim that Vivado has just run.
const reports = new Map();
if (evidenceDir) for (const name of ['before-timing.rpt','after-timing.rpt','utilization.rpt','implementation.tcl','clock.xdc']) {
  const path = join(evidenceDir, name);
  if (!existsSync(path)) throw Error('Missing report: ' + path);
  reports.set(name, readFileSync(path, 'utf8'));
}
let run;
for (const interpreter of [...new Set([process.env.PYTHON, 'python3', 'python'].filter(Boolean))]) {
  try {
    run = execFileSync(interpreter, ['rtl/sim/run_tests.py'], {cwd:rtl, encoding:'utf8', timeout:60000});
    break;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}
if (!run) throw Error('Python was not found. Set PYTHON to an interpreter command.');
const summary = run.match(/(\d+)\/(\d+) testbenches passed/);
if (!summary || summary[1] !== summary[2] || Number(summary[1]) === 0) throw Error('RTL regression did not pass completely.');
// Write only after the complete source set, optional reports and test run pass.
const evidence = join(root, 'assets/evidence');
mkdirSync(evidence, {recursive:true});
const snapshot = {repository:'spenchh/FPGA-foc-motor-control', commit, files};
writeFileSync(join(root, 'assets/js/source-data.js'),
  '// Generated by tools/sync-sources.mjs from the pinned RTL revision.\nwindow.SOURCE_DATA = ' + JSON.stringify(snapshot, null, 2) + ';\n');
for (const [name, content] of reports) writeFileSync(join(evidence, name), content);
const date = new Date().toISOString().slice(0,10);
const version = execFileSync('iverilog', ['-V'], {encoding:'utf8', stdio:['ignore','pipe','ignore']}).split('\n')[0];
writeFileSync(join(evidence, 'regression.txt'),
  `Icarus SystemVerilog directed regression\nSource commit: ${commit}\nChecked: ${date}\nTool: ${version}\nCommand: python3 rtl/sim/run_tests.py\n\n` +
  run.split('\n').filter(l => /^(Starting|PASS:|\d+\/\d+ testbenches passed)/.test(l)).join('\n') + '\n');
console.log(`Pinned ${files.length} sources at ${commit}; ${summary[0]}. Historical timing reports ${evidenceDir ? 'imported explicitly' : 'preserved'}.`);
