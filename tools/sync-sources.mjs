import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const root = resolve(import.meta.dirname, '..');
const rtl = resolve(process.argv[2] || '../fpga-motors');
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: rtl, encoding: 'utf8' }).trim();
const files = [];
for (const dir of ['rtl/design', 'rtl/verif', 'synth']) {
  for (const name of readdirSync(join(rtl, dir)).filter(n => n.endsWith('.sv')).sort()) {
    const path = `${dir}/${name}`;
    const code = readFileSync(join(rtl, path), 'utf8').replace(/\r\n/g, '\n');
    files.push({ path, name, code, sha256: createHash('sha256').update(code).digest('hex'),
      url: `https://github.com/spenchh/FPGA-foc-motor-control/blob/${commit}/${path}` });
  }
}
const target = join(root, 'assets/js/source-data.js');
mkdirSync(join(root, 'assets/js'), { recursive: true });
writeFileSync(target, `// Generated by tools/sync-sources.mjs from the pinned RTL revision.\nwindow.SOURCE_DATA = ${JSON.stringify({ repository: 'spenchh/FPGA-foc-motor-control', commit, files }, null, 2)};\n`);
const evidence = join(root, 'assets/evidence');
mkdirSync(evidence, { recursive: true });
const surg = 'C:/Users/HP/Documents/SURG';
for (const [from, to] of [
  ['fpga/synth_foc_wrapper_out/post_route_timing_summary.rpt', 'before-timing.rpt'],
  ['fpga/synth_foc_wrapper_pipelined_out/post_route_timing_summary.rpt', 'after-timing.rpt'],
  ['fpga/synth_foc_wrapper_pipelined_out/post_route_utilization_hierarchical.rpt', 'utilization.rpt'],
  ['fpga/synth_foc_wrapper_pipelined_nonproject.tcl', 'implementation.tcl'],
  ['fpga/foc_synth_clock.xdc', 'clock.xdc']
]) {
  // Remove local machine paths while preserving report values and endpoints.
  const text = readFileSync(join(surg, from), 'utf8').replaceAll('C:/Users/HP/Documents/SURG/', '<project>/');
  writeFileSync(join(evidence, to), text);
}
const run = execFileSync('python', ['rtl/sim/run_tests.py'], { cwd: rtl, encoding: 'utf8' });
if (!run.includes('13/13 testbenches passed')) throw Error('RTL regression did not pass');
writeFileSync(join(evidence, 'regression.txt'), `Icarus SystemVerilog directed regression\nSource commit: ${commit}\nChecked: 2026-10-23\nCommand: python rtl/sim/run_tests.py\n\n${run.split('\n').filter(l => /^(Starting|PASS:|13\/13)/.test(l)).join('\n')}\n`);
console.log(`Pinned ${files.length} sources at ${commit}; 13/13 testbenches passed.`);
